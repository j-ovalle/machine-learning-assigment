def main():
    stage = sys.argv[1].lower() if len(sys.argv) > 1 else "all"
    df = get_data()
    if stage in ("all", "eda"):
        run_eda(df)
    if stage in ("all", "model"):
        run_modeling(df)
    print("\n===PIPELINE COMPLETE===")


if __name__ == "__main__":
    main()
