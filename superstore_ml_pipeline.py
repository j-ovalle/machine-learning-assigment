# 1 + 2.  DATA LOADING, CLEANING & FEATURE ENGINEERING
# =========================================================================== #
def get_data():
    """Load, clean and feature-engineer the Superstore dataset."""
    print("\n[1] Loading and cleaning data ...")
    path = find_dataset()
    df = pd.read_csv(path, encoding="latin-1")
    print(f"  Loaded {df.shape[0]} rows x {df.shape[1]} columns from '{os.path.basename(path)}'")

    # Parse the date columns (source format is M/D/Y, e.g. 11/8/2016)
    df["Order Date"] = pd.to_datetime(df["Order Date"], format="%m/%d/%Y", errors="coerce")
    df["Ship Date"] = pd.to_datetime(df["Ship Date"], format="%m/%d/%Y", errors="coerce")

    print(f"  Missing values: {int(df.isna().sum().sum())} | "
          f"Duplicate rows: {int(df.duplicated().sum())}")
    df = df.drop_duplicates().reset_index(drop=True)

    print("\n[2] Engineering features ...")
    df["Shipping Days"] = (df["Ship Date"] - df["Order Date"]).dt.days
    df["Order Year"] = df["Order Date"].dt.year
    df["Order Month"] = df["Order Date"].dt.month
    df["Order Quarter"] = df["Order Date"].dt.quarter
    df["Profit Margin"] = df["Profit"] / df["Sales"]        # analytical field (NOT a model input)
    df["Is Profitable"] = (df["Profit"] > 0).astype(int)    # analytical flag
    print("  Added: Shipping Days, Order Year/Month/Quarter, Profit Margin, Is Profitable")
    return df


