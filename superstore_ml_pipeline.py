    profit_by_segment = df.groupby("Segment")["Profit"].sum().sort_values(ascending=False)
    disc_profit_corr = df["Discount"].corr(df["Profit"])
    disc_margin_corr = df["Discount"].corr(df["Profit Margin"])

    with open(os.path.join(OUT_DIR, "eda_summary.txt"), "w") as f:
        f.write("SUPERSTORE EDA SUMMARY\n======================\n")
