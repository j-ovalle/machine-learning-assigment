# 4-7.  MODELLING, EVALUATION & INTERPRETATION
# =========================================================================== #
def run_modeling(df):
    print("\n[4] Building preprocessing pipeline ...")
    model_df = df[NUMERIC_FEATURES + CATEGORICAL_FEATURES + [TARGET]].dropna().copy()

    # Outlier handling (Task 2): Sales and Profit are highly right/left-skewed with
    # extreme tails. We winsorise both monetary variables at the 1st/99th percentiles
    # so that a handful of exceptional transactions do not dominate the squared-error
    # loss and destabilise hold-out evaluation. ~2% of values are capped; the extreme
    # transactions remain visible in the (un-capped) EDA.
    for col in ["Sales", "Profit"]:
        lo, hi = model_df[col].quantile([0.01, 0.99])
        n_out = int(((model_df[col] < lo) | (model_df[col] > hi)).sum())
        model_df[col] = model_df[col].clip(lo, hi)
        print(f"  Winsorised {col} to [{lo:.2f}, {hi:.2f}] ({n_out} values capped)")

    X = model_df[NUMERIC_FEATURES + CATEGORICAL_FEATURES]
    y = model_df[TARGET]
    print(f"  Modelling matrix: {X.shape[0]} rows, {len(NUMERIC_FEATURES)} numeric + "
          f"{len(CATEGORICAL_FEATURES)} categorical features")

    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.20, random_state=RANDOM_STATE)
    print(f"  Train: {X_train.shape[0]} | Test: {X_test.shape[0]} (80/20 split)")

    preprocess = ColumnTransformer([
        ("num", StandardScaler(), NUMERIC_FEATURES),
        ("cat", OneHotEncoder(handle_unknown="ignore"), CATEGORICAL_FEATURES),
    ])

    print("\n[5] Training and tuning models ...")
    # Every model is wrapped in GridSearchCV (with >=1 candidate) so a single fit
    # yields BOTH the tuned estimator and the per-fold cross-validation scores,
    # avoiding redundant re-fitting. Grids are deliberately lean for runtime while
    # remaining representative of standard practice.
    models = {
        "Linear Regression": (LinearRegression(), {"m__fit_intercept": [True]}),
        "Ridge Regression": (Ridge(random_state=RANDOM_STATE), {"m__alpha": [1.0, 10.0, 100.0]}),
        "Lasso Regression": (Lasso(random_state=RANDOM_STATE, max_iter=5000), {"m__alpha": [0.1, 1.0, 10.0]}),
        "Random Forest": (RandomForestRegressor(random_state=RANDOM_STATE, n_jobs=-1),
                          {"m__n_estimators": [120], "m__max_depth": [None, 20]}),
        "Gradient Boosting": (GradientBoostingRegressor(random_state=RANDOM_STATE, max_depth=3),
                              {"m__n_estimators": [100], "m__learning_rate": [0.1]}),
    }

    cv = KFold(n_splits=5, shuffle=True, random_state=RANDOM_STATE)
    results, fitted, cv_scores = [], {}, {}

    for name, (estimator, grid) in models.items():
        pipe = Pipeline([("prep", preprocess), ("m", estimator)])
        gs = GridSearchCV(pipe, grid, scoring="r2", cv=cv, n_jobs=-1)
        gs.fit(X_train, y_train)
        best, best_params = gs.best_estimator_, gs.best_params_

        # Per-fold CV R^2 for the winning hyper-parameter combination
        bi = gs.best_index_
        folds = np.array([gs.cv_results_[f"split{i}_test_score"][bi] for i in range(cv.get_n_splits())])

        pred = best.predict(X_test)
        mae = mean_absolute_error(y_test, pred)
        mse = mean_squared_error(y_test, pred)
        rmse = float(np.sqrt(mse))
        r2 = r2_score(y_test, pred)

        shown = {k: v for k, v in best_params.items() if k != "m__fit_intercept"}
        results.append({"Model": name, "MAE": round(mae, 3), "MSE": round(mse, 2),
                        "RMSE": round(rmse, 3), "R2": round(r2, 4),
                        "CV_R2_mean": round(folds.mean(), 4), "CV_R2_std": round(folds.std(), 4),
                        "Best_Params": str(shown)})
        fitted[name] = best
        cv_scores[name] = folds
        print(f"  {name:<20} R2={r2:0.3f}  RMSE={rmse:7.2f}  MAE={mae:6.2f}  "
              f"CV_R2={folds.mean():0.3f}+/-{folds.std():0.3f}  params={shown}")

    res_df = pd.DataFrame(results).sort_values("R2", ascending=False).reset_index(drop=True)
    res_df.to_csv(os.path.join(OUT_DIR, "model_metrics.csv"), index=False)
    best_name = res_df.iloc[0]["Model"]
    best_model = fitted[best_name]
    print(f"\n  >>> Best model: {best_name} (R2={res_df.iloc[0]['R2']:.3f})")

    print("\n[6] Producing evaluation figures ...")
    # Fig 8: model comparison (R2 and RMSE)
    fig, ax = plt.subplots(1, 2, figsize=(12, 4.5))
    o1 = res_df.sort_values("R2")
    ax[0].barh(o1["Model"], o1["R2"], color=PRIMARY); ax[0].set(title="Test R² by Model", xlabel="R²")
    o2 = res_df.sort_values("RMSE", ascending=False)
    ax[1].barh(o2["Model"], o2["RMSE"], color=ACCENT); ax[1].set(title="Test RMSE by Model", xlabel="RMSE (USD)")
    savefig(fig, "fig08_model_comparison.png")

    # Fig 9: actual vs predicted (best model)
    pred_best = best_model.predict(X_test)
    fig, ax = plt.subplots(figsize=(6, 6))
    ax.scatter(y_test, pred_best, s=8, alpha=0.3, color=PRIMARY)
    lims = [min(y_test.min(), pred_best.min()), max(y_test.max(), pred_best.max())]
    ax.plot(lims, lims, color=ACCENT, lw=1.5)
    ax.set(title=f"Actual vs Predicted Profit - {best_name}",
           xlabel="Actual Profit (USD)", ylabel="Predicted Profit (USD)")
    savefig(fig, "fig09_actual_vs_predicted.png")

    # Fig 10: residual distribution
    resid = y_test - pred_best
    fig, ax = plt.subplots(figsize=(7, 4))
    ax.hist(resid, bins=80, color=PRIMARY); ax.axvline(0, color=ACCENT, lw=1.5)
    ax.set(title=f"Residuals - {best_name}", xlabel="Residual (USD)", ylabel="Frequency", xlim=(-400, 400))
    savefig(fig, "fig10_residuals.png")

    # Fig 11: feature importance / coefficients (best model)
    ohe = best_model.named_steps["prep"].named_transformers_["cat"]
    feat_names = NUMERIC_FEATURES + list(ohe.get_feature_names_out(CATEGORICAL_FEATURES))
    estimator = best_model.named_steps["m"]
    if hasattr(estimator, "feature_importances_"):
        imp, imp_label = estimator.feature_importances_, "Feature Importance"
    else:
        imp, imp_label = np.abs(estimator.coef_), "|Coefficient|"
    imp_series = pd.Series(imp, index=feat_names).sort_values(ascending=False).head(15)
    fig, ax = plt.subplots(figsize=(8, 6))
    ax.barh(imp_series.index[::-1], imp_series.values[::-1], color=PRIMARY)
    ax.set(title=f"Top 15 Predictors - {best_name}", xlabel=imp_label)
    savefig(fig, "fig11_feature_importance.png")

    # Fig 12: 5-fold cross-validation R2 distribution
    fig, ax = plt.subplots(figsize=(8, 4.5))
    names = list(cv_scores.keys())
    ax.boxplot([cv_scores[n] for n in names])
    ax.set_xticks(range(1, len(names) + 1)); ax.set_xticklabels(names, rotation=20, ha="right")
    ax.set(title="5-Fold Cross-Validation R² by Model", ylabel="R²")
    savefig(fig, "fig12_cv_scores.png")

    print("\n================= MODEL COMPARISON =================")
    print(res_df[["Model", "MAE", "RMSE", "R2", "CV_R2_mean", "CV_R2_std"]].to_string(index=False))
    print("===================================================")


# =========================================================================== #
# Entry point
